// Industry-standard preset theme starting points. Each preset defines a
// full palette for BOTH light and dark mode so the result looks coherent
// no matter which the user is currently viewing in. Applying a preset
// only fills the editor state — the admin must still Preview / Save to
// push the colors to the live app.
//
// Sidebar gradient convention (both modes): TOP = lighter, BOTTOM = darker.
// The user pill and connection warnings sit at the bottom, so pill
// backgrounds are picked to be one step lighter than the bottom stop for
// a subtle "card" effect and pill text colors are picked for AA contrast
// against the deepest bottom color.

export interface PresetTheme {
  key: string
  labelKey: string
  colors: Record<string, string>
}

