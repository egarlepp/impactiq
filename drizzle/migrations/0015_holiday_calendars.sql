-- Holiday calendars: shared library of country/locale holiday sets that can
-- be assigned to users so their capacity math excludes those days.

CREATE TABLE IF NOT EXISTS holiday_calendars (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code         text NOT NULL UNIQUE,   -- e.g. 'us', 'gb', 'de', 'fr', 'es', 'jp', 'pt', 'it'
  name         text NOT NULL,          -- e.g. 'United States federal holidays'
  locale       text NOT NULL,          -- e.g. 'en-US'
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS holiday_dates (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  calendar_id  uuid NOT NULL REFERENCES holiday_calendars(id) ON DELETE CASCADE,
  date         date NOT NULL,
  name         text NOT NULL,
  UNIQUE(calendar_id, date)
);
CREATE INDEX IF NOT EXISTS holiday_dates_calendar_idx ON holiday_dates (calendar_id, date);

CREATE TABLE IF NOT EXISTS user_holiday_calendars (
  user_id      uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  calendar_id  uuid NOT NULL REFERENCES holiday_calendars(id) ON DELETE CASCADE,
  PRIMARY KEY (user_id, calendar_id)
);

