#!/usr/bin/env node
// Parses drizzle/schema.ts and emits a markdown section per table plus an enums
// summary. The schema is Drizzle-idiomatic enough that simple regex parsing is
// reliable here — switching to ts-morph would be overkill for one doc.
//
// Run on demand: `node scripts/gen-db-schema.mjs > /tmp/db-schema.md`.
//
// Output is meant to be inlined into docs/db-schema.md.

import fs from 'node:fs'

const SCHEMA = fs.readFileSync('drizzle/schema.ts', 'utf8')

// --- Enums --------------------------------------------------------------
const enums = []
{
  const re = /export const (\w+Enum)\s*=\s*pgEnum\(\s*['"]([^'"]+)['"]\s*,\s*\[([\s\S]*?)\]\s*\)/g
  let m
  while ((m = re.exec(SCHEMA)) !== null) {
    const values = m[3].split(',').map((v) => v.trim().replace(/['"`]/g, '')).filter(Boolean)
    enums.push({ tsName: m[1], sqlName: m[2], values })
  }
}

// --- Tables -------------------------------------------------------------
// Matches `export const xxx = pgTable('sql_name', { ... }, optional-extras)`
// We greedily match through the first balanced `}` of the column literal.
const tables = []
{
  const re = /export const (\w+)\s*=\s*pgTable\(\s*['"]([^'"]+)['"]\s*,\s*\{([\s\S]*?)\}\s*(?:,\s*\([^)]*\)\s*=>\s*\[([\s\S]*?)\]\s*)?\)/g
  let m
  while ((m = re.exec(SCHEMA)) !== null) {
    const cols = parseColumns(m[3])
    const extras = m[4] ? parseExtras(m[4]) : { primaryKey: null, uniques: [] }
    tables.push({ tsName: m[1], sqlName: m[2], cols, ...extras })
  }
}

function parseColumns(body) {
  // Each column line: `tsName: type('sql_name', ...)...` with optional chained calls.
  // We capture: tsName, type, sqlName, plus the chained text for flags.
  const cols = []
  const re = /(\w+):\s*(\w+)\(\s*['"]([^'"]+)['"](?:,\s*(\{[^}]*\}|[^\)]*))?\)([\s\S]*?)(?=,\s*\n\s*\w+:|\s*$)/g
  let m
  while ((m = re.exec(body)) !== null) {
    const tsName = m[1]
    const type = m[2]
    const sqlName = m[3]
    const chained = m[5] || ''
    const isPk = /\.primaryKey\(/.test(chained)
    const isUnique = /\.unique\(/.test(chained)
    const notNull = /\.notNull\(/.test(chained)
    const hasDefault = /\.default(?:Random|Now)?\(/.test(chained)
    const fkMatch = chained.match(/\.references\(\(\)\s*=>\s*(\w+)\.(\w+)/)
    const fk = fkMatch ? `${fkMatch[1]}.${fkMatch[2]}` : null
    const onDeleteMatch = chained.match(/onDelete:\s*['"]([^'"]+)['"]/)
    const onDelete = onDeleteMatch ? onDeleteMatch[1] : null
    cols.push({ tsName, type, sqlName, isPk, isUnique, notNull, hasDefault, fk, onDelete })
  }
  return cols
}

function parseExtras(body) {
  let primaryKey = null
  const uniques = []
  const pkMatch = body.match(/primaryKey\(\{\s*columns:\s*\[([^\]]+)\]\s*\}\)/)
  if (pkMatch) primaryKey = pkMatch[1].split(',').map((c) => c.trim().replace(/^t\./, ''))
  const uRe = /unique\(\)\.on\(([^)]+)\)/g
  let u
  while ((u = uRe.exec(body)) !== null) {
    uniques.push(u[1].split(',').map((c) => c.trim().replace(/^t\./, '')))
  }
  return { primaryKey, uniques }
}

// --- Render -------------------------------------------------------------
console.log('# Auto-generated schema reference')
console.log()
console.log(`Source: \`drizzle/schema.ts\` · Generated by \`node scripts/gen-db-schema.mjs\`.`)
console.log(`Tables: **${tables.length}** · Enums: **${enums.length}**.`)
console.log()

console.log('## Enums')
console.log()
for (const e of enums) {
  console.log(`### \`${e.sqlName}\``)
  console.log()
  console.log('Values: ' + e.values.map((v) => `\`${v}\``).join(', '))
  console.log()
}

console.log('## Tables')
console.log()
for (const t of tables) {
  console.log(`### \`${t.sqlName}\``)
  console.log()
  console.log('| Column | Type | Nullable | Default | FK | Notes |')
  console.log('|--------|------|----------|---------|----|----|')
  for (const c of t.cols) {
    const nullable = c.notNull ? '—' : '✓'
    const def = c.hasDefault ? '✓' : '—'
    const fk = c.fk ? `\`${c.fk}\`${c.onDelete ? ` (on delete: ${c.onDelete})` : ''}` : ''
    const notes = []
    if (c.isPk) notes.push('PK')
    if (c.isUnique) notes.push('unique')
    console.log(`| \`${c.sqlName}\` | \`${c.type}\` | ${nullable} | ${def} | ${fk} | ${notes.join(', ')} |`)
  }
  if (t.primaryKey) {
    console.log()
    console.log(`**Composite PK:** ${t.primaryKey.map((p) => `\`${p}\``).join(', ')}`)
  }
  if (t.uniques.length > 0) {
    console.log()
    for (const u of t.uniques) console.log(`**Unique:** ${u.map((p) => `\`${p}\``).join(', ')}`)
  }
  console.log()
}
